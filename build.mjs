const today = new Date().toISOString().slice(0, 10);
if (siteUrl) {
  writeFileSync(join(dist, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${sitemap.flatMap((p) => LANGS.map((lang) => `  <url>
    <loc>${absUrl(lang, p.output)}</loc>
    <lastmod>${p.dateModified || p.datePublished || today}</lastmod>
${LANGS.map((l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${absUrl(l, p.output)}"/>`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${absUrl(DEFAULT_LANG, p.output)}"/>
  </url>`)).join('\n')}
</urlset>
`);
  writeFileSync(join(dist, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`);
}

if (missing.size) {
  console.error('Missing texts:\n' + [...missing].join('\n'));
  process.exit(1);
}
console.log(`Built ${pages.length * LANGS.length} pages into dist/` + (siteUrl ? ` (site URL: ${siteUrl})` : ' (set siteUrl for sitemap + canonical links)'));
if (!runtimeConfig.web3formsAccessKey) console.warn('Note: web3formsAccessKey is empty — the contact and newsletter forms will not send until you add it (see README).');
